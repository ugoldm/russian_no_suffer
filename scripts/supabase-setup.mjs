// Offline bundle for a fresh Supabase project. Never connects to a database.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const migrations = new URL("../supabase/migrations/", import.meta.url);
const files = readdirSync(migrations)
  .filter((name) => /^\d+_.+\.sql$/.test(name))
  .sort((a, b) => Number(a.split("_")[0]) - Number(b.split("_")[0]));
if (!files.length) throw new Error("Не найдены SQL-миграции.");
const sections = files.map((name) => {
  const sql = readFileSync(new URL(name, migrations), "utf8");
  // Outer transactions use standalone BEGIN/COMMIT. Function bodies use
  // BEGIN without a semicolon and remain unchanged.
  const boundaries = sql.match(/^\s*(?:begin|commit|rollback)\s*;\s*$/gim) || [];
  if (
    boundaries.length &&
    (boundaries.length !== 2 ||
      !/^\s*begin\s*;/i.test(boundaries[0]) ||
      !/^\s*commit\s*;/i.test(boundaries[1]))
  ) {
    throw new Error(`Проверьте границы транзакции в ${name}.`);
  }
  return `-- Migration: ${name}\n${sql.replace(/^\s*(?:begin|commit)\s*;\s*$/gim, "").trim()}\n`;
});
const sql = `-- Generated by npm run supabase:setup. Do not edit this file.
-- Only for a NEW database, in Supabase SQL Editor.
-- Includes ${files.length} migrations; does not configure Auth or import real tests.
begin;
do $$
begin
  if to_regclass('private.tests') is not null then
    raise exception 'База уже настроена. Применяйте только новые миграции, а не начальную установку.';
  end if;
end $$;

${sections.join("\n")}
commit;
`;
const outputDir = new URL("../imports/setup/", import.meta.url);
mkdirSync(outputDir, { recursive: true });
const output = new URL("supabase-init.sql", outputDir);
writeFileSync(output, sql);
console.log(`Подготовлено ${files.length} миграций: ${fileURLToPath(output)}`);
console.log("Выполните весь файл один раз в SQL Editor нового проекта Supabase.");
